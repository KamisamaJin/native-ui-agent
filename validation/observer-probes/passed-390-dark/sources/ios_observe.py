TEMPLATES = Path(__file__).resolve().parents[1] / "assets" / "ios-observer"


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def unique_node(nodes: list[dict], identifier: str) -> dict:
    matches = [n for n in nodes if n.get("identifier") == identifier]
    if len(matches) != 1:
        raise ValueError(f"{identifier!r} matched {len(matches)} nodes, expected exactly one")
    return matches[0]


def point_to_pixels(frame: dict, app_frame: dict, pixels: dict) -> dict:
    """Convert measured screen-point frames to image coordinates; never infer styles."""
    if app_frame["width"] <= 0 or app_frame["height"] <= 0:
        raise ValueError("App frame must have positive dimensions")
    sx, sy = pixels["width"] / app_frame["width"], pixels["height"] / app_frame["height"]
    return {"x": (frame["x"] - app_frame["x"]) * sx,
            "y": (frame["y"] - app_frame["y"]) * sy,
            "width": frame["width"] * sx, "height": frame["height"] * sy}


def coverage_status(coverage: dict) -> str:
    return "passed" if coverage.get("bottom_reached") is True and not coverage.get("missing_identifiers", ["unknown"]) else "failed"


def resolve_attachment(name: str, mapping: dict[str, str]) -> str:
    if name in mapping: return mapping[name]
    stem, suffix = os.path.splitext(name)
    matches = [exported for suggested, exported in mapping.items()
               if suggested.startswith(stem + "_") and suggested.endswith(suffix)]
    if len(matches) != 1:
        raise ValueError(f"Attachment {name!r} has {len(matches)} manifest matches")
    return matches[0]


def generate_project(directory: Path, bridge: Path, package: Path | None, product: str = "AlertToast") -> Path:
    directory.mkdir(parents=True, exist_ok=False)
    shutil.copyfile(TEMPLATES / "ObserverApp.swift", directory / "ObserverApp.swift")
    shutil.copyfile(TEMPLATES / "ObserverTests.swift", directory / "ObserverTests.swift")
    shutil.copyfile(bridge, directory / "Bridge.swift")
    ids = {name: hashlib.sha256(name.encode()).hexdigest()[:24].upper() for name in
           ["project", "main", "products", "app", "tests", "appProduct", "testsProduct", "appSource", "testsSource", "appFramework", "testsFramework", "appResources", "testsResources", "appFile", "bridgeFile", "testFile", "appBuild", "bridgeBuild", "testBuild", "projectConfigs", "appConfigs", "testConfigs", "projDebug", "projRelease", "appDebug", "appRelease", "testDebug", "testRelease", "package", "packageProduct", "packageBuild", "dependency", "proxy"]}
    q = lambda value: json.dumps(str(value))
    rows = []
    def add(key, body): rows.append(f"{ids[key]} = {{ {body} }};")
    ref = lambda key: ids[key]
    add("appFile", f"isa = PBXFileReference; lastKnownFileType = sourcecode.swift; path = ObserverApp.swift; sourceTree = \"<group>\";")
    add("bridgeFile", "isa = PBXFileReference; lastKnownFileType = sourcecode.swift; path = Bridge.swift; sourceTree = \"<group>\";")
    add("testFile", "isa = PBXFileReference; lastKnownFileType = sourcecode.swift; path = ObserverTests.swift; sourceTree = \"<group>\";")
    for build, file in [("appBuild", "appFile"), ("bridgeBuild", "bridgeFile"), ("testBuild", "testFile")]:
        add(build, f"isa = PBXBuildFile; fileRef = {ref(file)};")
    add("appProduct", "isa = PBXFileReference; explicitFileType = wrapper.application; path = ObserverApp.app; sourceTree = BUILT_PRODUCTS_DIR;")
    add("testsProduct", "isa = PBXFileReference; explicitFileType = wrapper.cfbundle; path = ObserverTests.xctest; sourceTree = BUILT_PRODUCTS_DIR;")
    add("main", f"isa = PBXGroup; children = ({ref('appFile')}, {ref('bridgeFile')}, {ref('testFile')}, {ref('products')}); sourceTree = \"<group>\";")
    add("products", f"isa = PBXGroup; children = ({ref('appProduct')}, {ref('testsProduct')}); name = Products; sourceTree = \"<group>\";")
    add("appSource", f"isa = PBXSourcesBuildPhase; buildActionMask = 2147483647; files = ({ref('appBuild')}, {ref('bridgeBuild')}); runOnlyForDeploymentPostprocessing = 0;")
    add("testsSource", f"isa = PBXSourcesBuildPhase; buildActionMask = 2147483647; files = ({ref('testBuild')}); runOnlyForDeploymentPostprocessing = 0;")
    for key in ["appResources", "testsResources"]:
        add(key, "isa = PBXResourcesBuildPhase; buildActionMask = 2147483647; files = (); runOnlyForDeploymentPostprocessing = 0;")
    if package:
        add("package", f"isa = XCLocalSwiftPackageReference; relativePath = {q(package.resolve())};")
        add("packageProduct", f"isa = XCSwiftPackageProductDependency; package = {ref('package')}; productName = {q(product)};")
        add("packageBuild", f"isa = PBXBuildFile; productRef = {ref('packageProduct')};")
    add("appFramework", f"isa = PBXFrameworksBuildPhase; buildActionMask = 2147483647; files = ({ref('packageBuild') if package else ''}); runOnlyForDeploymentPostprocessing = 0;")
    add("testsFramework", "isa = PBXFrameworksBuildPhase; buildActionMask = 2147483647; files = (); runOnlyForDeploymentPostprocessing = 0;")
    add("proxy", f"isa = PBXContainerItemProxy; containerPortal = {ref('project')}; proxyType = 1; remoteGlobalIDString = {ref('app')}; remoteInfo = ObserverApp;")
    add("dependency", f"isa = PBXTargetDependency; target = {ref('app')}; targetProxy = {ref('proxy')};")
    for target, configs, phases, name, productkey, kind, deps in [
        ("app", "appConfigs", ["appSource", "appFramework", "appResources"], "ObserverApp", "appProduct", "com.apple.product-type.application", ""),
        ("tests", "testConfigs", ["testsSource", "testsFramework", "testsResources"], "ObserverTests", "testsProduct", "com.apple.product-type.bundle.ui-testing", ref("dependency"))]:
        add(target, f"isa = PBXNativeTarget; buildConfigurationList = {ref(configs)}; buildPhases = ({','.join(ref(p) for p in phases)}); buildRules = (); dependencies = ({deps}); name = {name}; productName = {name}; productReference = {ref(productkey)}; productType = {q(kind)}; packageProductDependencies = ({ref('packageProduct') if package and target == 'app' else ''});")
    common = "SDKROOT = iphonesimulator; IPHONEOS_DEPLOYMENT_TARGET = 17.0; SWIFT_VERSION = 5.0; CODE_SIGNING_ALLOWED = NO; TARGETED_DEVICE_FAMILY = 1; GENERATE_INFOPLIST_FILE = YES; ENABLE_USER_SCRIPT_SANDBOXING = YES;"
    for key, name in [("projDebug", "Debug"), ("projRelease", "Release")]:
        add(key, f"isa = XCBuildConfiguration; buildSettings = {{ {common} }}; name = {name};")
    for key, name in [("appDebug", "Debug"), ("appRelease", "Release")]:
        add(key, f"isa = XCBuildConfiguration; buildSettings = {{ {common} PRODUCT_BUNDLE_IDENTIFIER = org.nativeobserver.app; PRODUCT_NAME = ObserverApp; INFOPLIST_KEY_UILaunchScreen_Generation = YES; INFOPLIST_KEY_UIApplicationSceneManifest_Generation = YES; }}; name = {name};")
    for key, name in [("testDebug", "Debug"), ("testRelease", "Release")]:
        add(key, f"isa = XCBuildConfiguration; buildSettings = {{ {common} PRODUCT_BUNDLE_IDENTIFIER = org.nativeobserver.tests; PRODUCT_NAME = ObserverTests; TEST_TARGET_NAME = ObserverApp; }}; name = {name};")
    for key, values in [("projectConfigs", ["projDebug", "projRelease"]), ("appConfigs", ["appDebug", "appRelease"]), ("testConfigs", ["testDebug", "testRelease"])]:
        add(key, f"isa = XCConfigurationList; buildConfigurations = ({','.join(ref(v) for v in values)}); defaultConfigurationIsVisible = 0; defaultConfigurationName = Debug;")
    add("project", f"isa = PBXProject; attributes = {{ LastUpgradeCheck = 2700; TargetAttributes = {{ {ref('tests')} = {{ TestTargetID = {ref('app')}; }}; }}; }}; buildConfigurationList = {ref('projectConfigs')}; compatibilityVersion = \"Xcode 14.0\"; developmentRegion = en; knownRegions = (en, Base); mainGroup = {ref('main')}; productRefGroup = {ref('products')}; projectDirPath = \"\"; projectRoot = \"\"; targets = ({ref('app')},{ref('tests')}); packageReferences = ({ref('package') if package else ''});")
    project = directory / "Observer.xcodeproj"
    project.mkdir()
    (project / "project.pbxproj").write_text("// !$*UTF8*$!\n{ archiveVersion = 1; classes = {}; objectVersion = 56; objects = {\n" + "\n".join(rows) + f"\n}}; rootObject = {ref('project')}; }}\n")
    schemes = project / "xcshareddata" / "xcschemes"; schemes.mkdir(parents=True)
    def br(key, name, file):
        return f'<BuildableReference BuildableIdentifier="primary" BlueprintIdentifier="{ref(key)}" BuildableName="{file}" BlueprintName="{name}" ReferencedContainer="container:Observer.xcodeproj"/>'
    (schemes / "Observer.xcscheme").write_text(f'''<?xml version="1.0" encoding="UTF-8"?><Scheme LastUpgradeVersion="2700" version="1.3"><BuildAction parallelizeBuildables="YES" buildImplicitDependencies="YES"><BuildActionEntries><BuildActionEntry buildForTesting="YES" buildForRunning="YES" buildForProfiling="YES" buildForArchiving="YES" buildForAnalyzing="YES">{br('app','ObserverApp','ObserverApp.app')}</BuildActionEntry><BuildActionEntry buildForTesting="YES" buildForRunning="NO" buildForProfiling="NO" buildForArchiving="NO" buildForAnalyzing="YES">{br('tests','ObserverTests','ObserverTests.xctest')}</BuildActionEntry></BuildActionEntries></BuildAction><TestAction buildConfiguration="Debug" selectedDebuggerIdentifier="Xcode.DebuggerFoundation.Debugger.LLDB" selectedLauncherIdentifier="Xcode.IDEFoundation.Launcher.LLDB" shouldUseLaunchSchemeArgsEnv="YES"><Testables><TestableReference skipped="NO">{br('tests','ObserverTests','ObserverTests.xctest')}</TestableReference></Testables></TestAction><LaunchAction buildConfiguration="Debug"/></Scheme>''')
    return project


def command(args: list[str], env: dict, log: Path | None = None) -> subprocess.CompletedProcess:
    result = subprocess.run(args, env=env, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if log: log.write_text(result.stdout)
    return result


def run(args) -> int:
    output = Path(args.output).resolve()
    if output.exists(): raise ValueError(f"Output must be fresh: {output}")
    output.mkdir(parents=True)
    bridge = Path(args.bridge).resolve()
    package = Path(args.package).resolve() if args.package else None
    config = json.loads(Path(args.fixtures).read_text())
    actions = json.loads(Path(args.actions).read_text()) if args.actions else []
    if config.get("width", 390) not in (320, 390): raise ValueError("width must be 320 or 390 logical points")
    if not isinstance(config.get("initial"), dict) or not isinstance(config.get("updates", []), list): raise ValueError("initial object and updates array required")
    if not all(isinstance(f, dict) for f in config.get("updates", [])): raise ValueError("every update must be an object")
    if config.get("theme", "light") not in ("light", "dark"): raise ValueError("theme must be light or dark")
    if config.get("direction", "ltr") not in ("ltr", "rtl"): raise ValueError("direction must be ltr or rtl")
    if "canvas_color" in config and not re.fullmatch(r"#[0-9a-fA-F]{6}", str(config["canvas_color"])): raise ValueError("canvas_color must be #RRGGBB")
    allowed_types = ["xSmall", "small", "medium", "large", "xLarge", "xxLarge", "xxxLarge"] + [f"accessibility{i}" for i in range(1, 6)]
    if config.get("dynamic_type", "large") not in allowed_types: raise ValueError("unknown dynamic_type")
    if not isinstance(actions, list) or len(actions) > 40: raise ValueError("actions must be an array of at most 40 bounded actions")
    env = dict(os.environ, DEVELOPER_DIR=args.developer_dir)
    manifest = {"schema_version": 1, "status": "error", "simulator": args.simulator, "started_at": time.time(),
                "bridge": str(bridge), "package": str(package) if package else None, "source_hashes": {}, "image_hashes": {}, "native_test_count": 0}
    files = [bridge, TEMPLATES / "ObserverApp.swift", TEMPLATES / "ObserverTests.swift", Path(__file__).resolve()]
    if package:
        files += [package / "Package.swift"] + sorted(p for p in (package / "Sources").rglob("*") if p.is_file())
    manifest["source_hashes"] = {str(p): digest(p) for p in files}
    manifest["input_hashes"] = {"fixtures": digest(Path(args.fixtures))}
    if args.actions: manifest["input_hashes"]["actions"] = digest(Path(args.actions))
    (output / "fixtures.json").write_text(json.dumps(config, indent=2, ensure_ascii=False))
    (output / "actions.json").write_text(json.dumps(actions, indent=2, ensure_ascii=False))
    project = generate_project(output / "project", bridge, package, args.product)
    derived = output / "DerivedData"
    try:
        command(["xcrun", "simctl", "boot", args.simulator], env, output / "boot.log")
        boot = command(["xcrun", "simctl", "bootstatus", args.simulator, "-b"], env, output / "bootstatus.log")
        if boot.returncode: raise RuntimeError("Simulator did not boot; see bootstatus.log")
        build_args = ["xcodebuild", "build-for-testing", "-project", str(project), "-scheme", "Observer", "-configuration", "Debug", "-sdk", args.sdk,
                      "-destination", f"platform=iOS Simulator,id={args.simulator}", "-derivedDataPath", str(derived), "-resultBundlePath", str(output / "build.xcresult"), "CODE_SIGNING_ALLOWED=NO"]
        manifest["build_command"] = build_args
        build = command(build_args, env, output / "build.log")
        manifest["build_exit_code"] = build.returncode
        if build.returncode: raise RuntimeError("Native build failed; see build.log")
        runs = list((derived / "Build" / "Products").glob("*.xctestrun"))
        if len(runs) != 1: raise RuntimeError(f"Expected one xctestrun, got {len(runs)}")
        runfile = runs[0]
        with runfile.open("rb") as stream: testplan = plistlib.load(stream)
        transport = {"OBSERVER_CONFIG_BASE64": base64.b64encode(json.dumps(config).encode()).decode(),
                     "OBSERVER_ACTIONS_BASE64": base64.b64encode(json.dumps(actions).encode()).decode()}
        def inject(value):
            if isinstance(value, dict):
                if "TestBundlePath" in value:
                    value.setdefault("EnvironmentVariables", {}).update(transport)
                for child in list(value.values()): inject(child)
            elif isinstance(value, list):
                for child in value: inject(child)
        inject(testplan)
        with runfile.open("wb") as stream: plistlib.dump(testplan, stream)
        test_args = ["xcodebuild", "test-without-building", "-xctestrun", str(runfile), "-destination", f"platform=iOS Simulator,id={args.simulator}",
                     "-resultBundlePath", str(output / "test.xcresult"), "-parallel-testing-enabled", "NO", "-maximum-concurrent-test-simulator-destinations", "1"]
        manifest["test_command"] = test_args
        test = command(test_args, env, output / "test.log")
        manifest["test_exit_code"] = test.returncode
        result_bundle = output / "test.xcresult"
        summary = command(["xcrun", "xcresulttool", "get", "test-results", "summary", "--path", str(result_bundle), "--format", "json"], env, output / "native-summary.json")
        if summary.returncode == 0:
            summary_json = json.loads(summary.stdout)
            manifest["native_test_count"] = summary_json.get("totalTestCount", 0)
            manifest["native_summary"] = summary_json
        exported = output / "attachments"
        exported_result = command(["xcrun", "xcresulttool", "export", "attachments", "--path", str(result_bundle), "--output-path", str(exported)], env, output / "export.log")
        if exported_result.returncode: raise RuntimeError("Could not export native test evidence")
        attachment_manifest = json.loads((exported / "manifest.json").read_text())
        attachment_map = {}
        def collect(value):
            if isinstance(value, dict):
                if "suggestedHumanReadableName" in value and "exportedFileName" in value:
                    attachment_map[value["suggestedHumanReadableName"]] = value["exportedFileName"]
                for v in value.values(): collect(v)
            elif isinstance(value, list):
                for v in value: collect(v)
        collect(attachment_manifest)
        observation = None
        for path in exported.glob("*"):
            if path.suffix == ".json" and path.name != "manifest.json":
                try:
                    candidate = json.loads(path.read_text())
                    if isinstance(candidate, dict) and "snapshots" in candidate: observation = candidate; break
                except (UnicodeDecodeError, json.JSONDecodeError): pass
        if observation is None: raise RuntimeError("Native test produced no observation JSON; see test.log and attachments")
        for snap in observation["snapshots"]:
            name = snap["screenshot_attachment"]
            # xcresulttool supplies a manifest so no screenshot is guessed from ordering.
            exported_name = resolve_attachment(name, attachment_map)
            if not (exported / exported_name).is_file(): raise RuntimeError(f"Missing exported screenshot: {exported_name}")
            snap["screenshot"] = str(Path("attachments") / exported_name)
            for node in snap["nodes"]:
                node["image_frame"] = point_to_pixels(node["frame"], snap["app_frame"], snap["screenshot_pixels"])
        scroll_snapshots = [s for s in observation["snapshots"] if "scroll-" in s["name"] or "-reveal-" in s["name"]]
        key_snapshots = {"top": observation["snapshots"][0], "bottom": observation["snapshots"][-1]}
        if scroll_snapshots: key_snapshots["middle"] = scroll_snapshots[len(scroll_snapshots) // 2]
        observation["coverage_screenshots"] = {key: {"snapshot_index": snap["index"], "name": snap["name"], "screenshot": snap.get("screenshot")} for key, snap in key_snapshots.items()}
        (output / "observation.json").write_text(json.dumps(observation, indent=2, ensure_ascii=False))
        manifest["image_hashes"] = {str(p.relative_to(output)): digest(p) for p in sorted(exported.glob("*.png"))}
        manifest["coverage"] = observation["coverage"]
        manifest["actual_environment"] = observation["snapshots"][0]["runtime"].get("actual_environment")
        manifest["actual_viewport"] = observation["snapshots"][0]["viewport"]
        manifest["screenshot_pixels"] = observation["snapshots"][0]["screenshot_pixels"]
        complete = coverage_status(observation["coverage"]) == "passed"
        manifest["status"] = "passed" if test.returncode == 0 and manifest["native_test_count"] > 0 and observation["status"] == "passed" and complete else "failed"
    except Exception as exc:
        manifest["error"] = str(exc)
    manifest["finished_at"] = time.time()
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False))
    print(json.dumps({"status": manifest["status"], "output": str(output), "native_test_count": manifest["native_test_count"], "error": manifest.get("error")}, indent=2))
    return 0 if manifest["status"] == "passed" else 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("run")
    p.add_argument("--bridge", required=True)
    p.add_argument("--package")
    p.add_argument("--product", default="AlertToast")
    p.add_argument("--fixtures", required=True)
    p.add_argument("--actions")
    p.add_argument("--simulator", required=True)
    p.add_argument("--output", required=True)
    p.add_argument("--developer-dir", default="/Applications/Xcode.app/Contents/Developer")
    p.add_argument("--sdk", default="iphonesimulator")
    args = parser.parse_args()
    try: return run(args)
    except (ValueError, OSError) as exc:
        print(str(exc), file=sys.stderr); return 2


if __name__ == "__main__":
    raise SystemExit(main())
