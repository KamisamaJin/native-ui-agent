#!/usr/bin/env python3
"""Recompute actual planner selections and default adoption from original artifacts."""
import json
import study as s
import design_contract as d,retest_plan,requirement_routes as routes
R=s.R

def main():
 assignment=s.read(R/'private/assignment.json');rows=[]
 for unit,cfg in assignment['units'].items():
  w=R/'cache'/unit;session=s.read(R/'handoff'/unit/'SESSION-original.json');s.verify_dir(R/'handoff'/unit)
  native=[];cycles=[]
  roots=[R/'feedback'/unit,R/'corpora'/unit/'final-public']
  if cfg['mode']=='default':roots.append(R/'handoff'/unit)
  for folder in roots:
   if not folder.exists():continue
   for path in sorted(folder.rglob('cycle.json')):
    cycle=s.read(path);base=path.parent;pl=next(v for v in path.parts if v in ['ios','android']);case=base.parent.name if base.name=='intake'else base.name
    scope=R/'design/public';approval=s.read(scope/'approval.json');plan=s.read(scope/'compiled'/case/pl/'plan.json');lock=s.read(scope/'design-lock.json')
    prior=session['previous'][pl][case];ticket=session['adoptions'][pl][case]
    original=R/'corpora/initial/public'/pl/case;receipt=s.read(original/'result.json')
    assert s.sha(original/'result.json')==prior['sha256']
    adoption=R/'handoff'/unit/pl/case/'adoption.json';assert s.sha(adoption)==ticket['sha256'];adopted=s.read(adoption)
    before=s.read(original/'source-before.json');assert adopted['original_receipt_sha256']==prior['sha256']and adopted['source_sha256']==d.digest(before)==receipt['source_sha256']
    report=s.read(original/'automatic.json');obs=s.read(original/'native/observation.json');execution=s.read(original/'execution.json')
    files=s.read(R/'submissions'/unit/'final/seal.json')['files']
    now={str(i)+'/'+key[len(prefix)+1:]:h for i,prefix in enumerate(s.ROOTS)for key,h in files.items()if key.startswith(prefix+'/')}
    coverage=routes.audit(lock,approval['design_lock_sha256'],plan,s.read(scope/'routes.json'),approval['routes_sha256'])
    expected=retest_plan.unresolved(coverage,plan,report,changed_files=sorted(k for k in set(before)|set(now)if before.get(k)!=now.get(k)),source_before=d.digest(before),source_after=d.digest(now),final=cycle['final'],selected_states=execution['selected_states'])
    assert s.read(base/'retest-plan.json')==expected,str(path)
    assert s.read(base/'before-routes.json')==routes.route_findings(coverage,plan,report,obs,execution=execution)
    if cycle['native_executed']:
     actual=s.read(base/'capture/execution.json');assert actual['selected_states']==expected['states'];assert actual['parent_plan_sha256']==d.digest(plan)
    cycles.append({'path':str(path.relative_to(R)),'intake':cycle['intake'],'final':cycle['final'],'native_executed':cycle['native_executed'],'states':expected['states'],'original_failed':len(expected['original_failed_ids']),'original_unknown':len(expected['original_unknown_ids']),'source_changed':expected['source_changed'],'trace':cycle['trace']})
  for folder in roots[:2]:
   if not folder.exists():continue
   for path in sorted(folder.rglob('result.json')):
    if not(path.parent/'execution.json').is_file():continue
    receipt=s.read(path);execution=s.read(path.parent/'execution.json')
    native.append({'path':str(path.relative_to(R)),'platform':execution['platform'],'selected_states':execution['selected_states'],'scope':execution['scope'],'wall_seconds':receipt['finishedAtUnix']-receipt['startedAtUnix'],'source_sha256':receipt['source_sha256'],'status':receipt['status']})
  rows.append({'unit':unit,'condition':cfg['mode'],'native_runs':native,'default_cycles':cycles,'planner_calls':len(cycles),'routing_before_calls':len(cycles),'diagnostics_before_calls':len(cycles),'routing_after_calls':sum(v['native_executed']for v in cycles),'actual_source_changed':s.read(R/'submissions'/unit/'final/seal.json')['files']!=s.read(R/'submissions/initial/seal.json')['files']})
 return {'arms':rows,'scope':'Runtime adoption and exact selection replay; pending qualitative actuals are still unknown in original acquisition reports. No product-detection or speed credit is generated by this audit.'}
if __name__=='__main__':print(json.dumps(main(),indent=2))
