    if package:
        add("package", f"isa = XCLocalSwiftPackageReference; relativePath = {q(package.resolve())};")
        add("packageProduct", f"isa = XCSwiftPackageProductDependency; package = {ref('package')}; productName = {q(product)};")
        add("packageBuild", f"isa = PBXBuildFile; productRef = {ref('packageProduct')};")
    add("appFramework", f"isa = PBXFrameworksBuildPhase; buildActionMask = 2147483647; files = ({ref('packageBuild') if package else ''}); runOnlyForDeploymentPostprocessing = 0;")
    add("testsFramework", "isa = PBXFrameworksBuildPhase; buildActionMask = 2147483647; files = (); runOnlyForDeploymentPostprocessing = 0;")
    add("proxy", f"isa = PBXContainerItemProxy; containerPortal = {ref('project')}; proxyType = 1; remoteGlobalIDString = {ref('app')}; remoteInfo = ObserverApp;")
    add("dependency", f"isa = PBXTargetDependency; target = {ref('app')}; targetProxy = {ref('proxy')};")
    for target, configs, phases, name, productkey, kind, deps in [
        ("app", "appConfigs", ["appSource", "appFramework", "appResources"], "ObserverApp", "appProduct", "com.apple.product-type.application", ""),
        ("tests", "testConfigs", ["testsSource", "testsFramework", "testsResources"], "ObserverTests", "testsProduct", "com.apple.product-type.bundle.ui-testing", ref("dependency"))]:
        add(target, f"isa = PBXNativeTarget; buildConfigurationList = {ref(configs)}; buildPhases = ({','.join(ref(p) for p in phases)}); buildRules = (); dependencies = ({deps}); name = {name}; productName = {name}; productReference = {ref(productkey)}; productType = {q(kind)}; packageProductDependencies = ({ref('packageProduct') if package and target == 'app' else ''});")
