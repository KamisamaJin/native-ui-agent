    project = directory / "Observer.xcodeproj"
    project.mkdir()
    (project / "project.pbxproj").write_text("// !$*UTF8*$!\n{ archiveVersion = 1; classes = {}; objectVersion = 56; objects = {\n" + "\n".join(rows) + f"\n}}; rootObject = {ref('project')}; }}\n")
