    for build, file in [("appBuild", "appFile"), ("bridgeBuild", "bridgeFile"), ("testBuild", "testFile")]:
        add(build, f"isa = PBXBuildFile; fileRef = {ref(file)};")
    add("appProduct", "isa = PBXFileReference; explicitFileType = wrapper.application; path = ObserverApp.app; sourceTree = BUILT_PRODUCTS_DIR;")
