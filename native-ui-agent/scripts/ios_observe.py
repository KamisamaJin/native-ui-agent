    directory.mkdir(parents=True, exist_ok=False)
    shutil.copyfile(TEMPLATES / "ObserverApp.swift", directory / "ObserverApp.swift")
    shutil.copyfile(TEMPLATES / "ObserverTests.swift", directory / "ObserverTests.swift")
    shutil.copyfile(bridge, directory / "Bridge.swift")
    ids = {name: hashlib.sha256(name.encode()).hexdigest()[:24].upper() for name in
           ["project", "main", "products", "app", "tests", "appProduct", "testsProduct", "appSource", "testsSource", "appFramework", "testsFramework", "appResources", "testsResources", "appFile", "bridgeFile", "testFile", "appBuild", "bridgeBuild", "testBuild", "projectConfigs", "appConfigs", "testConfigs", "projDebug", "projRelease", "appDebug", "appRelease", "testDebug", "testRelease", "package", "packageProduct", "packageBuild", "dependency", "proxy"]}
