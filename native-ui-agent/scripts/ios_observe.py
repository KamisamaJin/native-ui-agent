def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def unique_node(nodes: list[dict], identifier: str) -> dict:
    matches = [n for n in nodes if n.get("identifier") == identifier]
    if len(matches) != 1:
        raise ValueError(f"{identifier!r} matched {len(matches)} nodes, expected exactly one")
    return matches[0]


def point_to_pixels(frame: dict, app_frame: dict, pixels: dict) -> dict:
    """Convert measured screen-point frames to image coordinates; never infer styles."""
    # Invalid native geometry is unavailable; never coerce it to zero pixels.
    if any(not isinstance(app_frame.get(k), (int, float)) or not math.isfinite(app_frame[k]) for k in ("x", "y", "width", "height")):
        raise ValueError("App frame must be finite")
    if any(not isinstance(frame.get(k), (int, float)) or not math.isfinite(frame[k]) for k in ("x", "y", "width", "height")):
        return None
    if app_frame["width"] <= 0 or app_frame["height"] <= 0:
        raise ValueError("App frame must have positive dimensions")
    sx, sy = pixels["width"] / app_frame["width"], pixels["height"] / app_frame["height"]
    return {"x": (frame["x"] - app_frame["x"]) * sx,
            "y": (frame["y"] - app_frame["y"]) * sy,
            "width": frame["width"] * sx, "height": frame["height"] * sy}


def coverage_status(coverage: dict) -> str:
    return "passed" if coverage.get("bottom_reached") is True and not coverage.get("missing_identifiers", ["unknown"]) else "failed"


def resolve_attachment(name: str, mapping: dict[str, str]) -> str:
    if name in mapping: return mapping[name]
    stem, suffix = os.path.splitext(name)
    matches = [exported for suggested, exported in mapping.items()
               if suggested.startswith(stem + "_") and suggested.endswith(suffix)]
    if len(matches) != 1:
        raise ValueError(f"Attachment {name!r} has {len(matches)} manifest matches")
    return matches[0]


